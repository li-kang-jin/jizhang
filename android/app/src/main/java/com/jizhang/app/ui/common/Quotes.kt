/**
 * 当天的一句：按「距 1970-01-01 的天数」取模。
 *
 * 用日期取模而不是随机：同一天里卡片怎么重组、页面怎么进出，都是同一句，
 * 换天才换 —— 随机会让这行字在滚动时跳来跳去，看起来像故障。
 */
fun quoteOfDay(date: LocalDate = LocalDate.now()): Quote {
    val index = Math.floorMod(date.toEpochDay(), QUOTES.size.toLong()).toInt()
    return QUOTES[index]
}
